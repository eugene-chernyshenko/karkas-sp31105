def _spacing_idx(spacing_mm: int) -> int:
    try:
        return SPACINGS.index(int(spacing_mm))
    except ValueError:
        raise ValueError(f"шаг {spacing_mm} мм отсутствует в таблицах СП (только 300/400/600)")


def _snow_key(snow_kpa: float) -> float:
    """Округление снеговой нагрузки ВВЕРХ до ближайшей табличной колонки."""
    for s in SNOW_COLS:
        if snow_kpa <= s + 1e-9:
            return s
    raise ValueError(f"снеговая нагрузка {snow_kpa} кПа > 3,0 кПа — таблицы СП неприменимы, нужен расчёт")


def joist_max_span(section: str, spacing_mm: int, *, table: str = "B1",
                   bracing: str = "hv") -> float:
    """Максимальный пролёт балки перекрытия, м. table: B1 | B2 | B3."""
    i = _spacing_idx(spacing_mm)
    if table == "B3":
        return T_B3[section][i]
    src = T_B1 if table == "B1" else T_B2
    return src[bracing][section][i]


def rafter_max_span(section: str, spacing_mm: int, snow_kpa: float) -> float:
    """Максимальный пролёт стропила (горизонтальная проекция), м. Табл. Б-6/Б-7."""
    return T_B6_7[_snow_key(snow_kpa)][section][_spacing_idx(spacing_mm)]


def roof_beam_max_span(section: str, spacing_mm: int, snow_kpa: float) -> float:
    """Максимальный пролёт кровельной балки плоской крыши, м. Табл. Б-4/Б-5."""
    return T_B4_5[_snow_key(snow_kpa)][section][_spacing_idx(spacing_mm)]


def ridge_beam_max_span(built_up: str, snow_kpa: float, tributary_m: float = 4.9) -> float:
    """Максимальный пролёт коньковой балки составного сечения, м. Табл. Б-11.
    built_up: '4x235' = 4 доски 38x235."""
    base = T_B11[built_up][SNOW_COLS.index(_snow_key(snow_kpa))]
    if tributary_m <= 3.7:
        base *= 1.10
    elif tributary_m <= 4.3:
        base *= 1.05
    return round(base, 3)


def girder_max_span(built_up: str, tributary_m: float, storeys: int) -> float:
    """Максимальный пролёт составного прогона в свету, м. Табл. Б-8/Б-9/Б-10.
    Линейная интерполяция по ширине грузовой площади."""
    rows = T_GIRDER[storeys]
    j = _GIRDER_COLS.index(built_up)
    if tributary_m <= rows[0][0]:
        return rows[0][1][j]
    if tributary_m >= rows[-1][0]:
        return rows[-1][1][j]
    for (w0, v0), (w1, v1) in zip(rows, rows[1:]):
        if w0 <= tributary_m <= w1:
            k = (tributary_m - w0) / (w1 - w0)
            return round(v0[j] + k * (v1[j] - v0[j]), 3)
    raise ValueError(tributary_m)


def lintel_max_span(depth_mm: int, load_case: str, *, snow_kpa: float = 1.0,
                    wall: str = "external", sheathed: bool = True,
                    joists_span_full_width: bool = False) -> float | None:
    """Максимальный пролёт перемычки 2х(38 x depth), м. Табл. Б-12 / Б-13.

    load_case: 'attic' | 'roof' | 'roof+1' | 'roof+2' | 'roof+3'
    sheathed  — каркас с жёсткой обшивкой (Б-13, только наружные стены).
    Возвращает None, если сочетание не нормируется.
    """
    if wall == "internal":
        v = T_B12[load_case][depth_mm][5]
    elif sheathed and load_case in T_B13:
        v = T_B13[load_case][depth_mm][SNOW_COLS.index(_snow_key(snow_kpa))]
    else:
        v = T_B12[load_case][depth_mm][SNOW_COLS.index(_snow_key(snow_kpa))]
    if v is None:
        return None
    if joists_span_full_width:
        v *= {"attic": 1.0, "roof": 1.0, "roof+1": 0.85, "roof+2": 0.80, "roof+3": 0.75}[load_case]
    return round(v, 3)


def pick_joist(span_m: float, spacing_mm: int, *, table: str = "B1",
               bracing: str = "hv") -> str | None:
    """Наименьшее сечение балки, перекрывающее пролёт."""
    for d in JOIST_DEPTHS:
        s = fmt(38, d)
        if joist_max_span(s, spacing_mm, table=table, bracing=bracing) >= span_m - 1e-9:
            return s
    return None


def pick_rafter(span_m: float, spacing_mm: int, snow_kpa: float) -> str | None:
    for d in JOIST_DEPTHS:
        s = fmt(38, d)
        if rafter_max_span(s, spacing_mm, snow_kpa) >= span_m - 1e-9:
            return s
    return None


def pick_roof_beam(span_m: float, spacing_mm: int, snow_kpa: float) -> str | None:
    for d in JOIST_DEPTHS:
        s = fmt(38, d)
        if roof_beam_max_span(s, spacing_mm, snow_kpa) >= span_m - 1e-9:
            return s
    return None


def pick_lintel(span_m: float, load_case: str, **kw) -> int | None:
    """Наименьшая высота сечения перемычки 2х(38xh), перекрывающая пролёт."""
    for d in JOIST_DEPTHS:
        v = lintel_max_span(d, load_case, **kw)
        if v is not None and v >= span_m - 1e-9:
            return d
    return None


def pick_ridge_beam(span_m: float, snow_kpa: float, tributary_m: float = 4.9) -> str | None:
    for s in ["3x184", "4x184", "5x184", "3x235", "4x235", "5x235", "3x286", "4x286", "5x286"]:
        if ridge_beam_max_span(s, snow_kpa, tributary_m) >= span_m - 1e-9:
            return s
    return None


def pick_girder(span_m: float, tributary_m: float, storeys: int) -> str | None:
    for s in _GIRDER_COLS:
        if girder_max_span(s, tributary_m, storeys) >= span_m - 1e-9:
            return s
    return None


def stud_options(wall: str, load_case: str) -> list[tuple[str, int, float, bool]]:
    return T7_1.get((wall, load_case), [])


def _not_weaker(cand: str, minimum: str) -> bool:
    """Сечение cand не слабее минимального: обе стороны не меньше (с учётом поворота)."""
    a = sorted(sec(cand))
    b = sorted(sec(minimum))
    return a[0] >= b[0] and a[1] >= b[1]


def check_stud(section: str, spacing_mm: int, free_height_m: float,
               wall: str, load_case: str, sheathed: bool = True) -> tuple[bool, str]:
    """Проверка стойки по таблице 7-1.

    Таблица задаёт МИНИМАЛЬНЫЕ сечения и МАКСИМАЛЬНЫЕ шаги, поэтому сечение крупнее
    табличного при том же (или меньшем) шаге считается соответствующим.
    """
    opts = stud_options(wall, load_case)
    if not opts:
        return False, f"нет строки табл. 7-1 для ({wall}, {load_case})"
    best = None
    for s, max_sp, max_h, _flat in opts:
        if spacing_mm <= max_sp and _not_weaker(section, s):
            if best is None or max_h > best[2]:
                best = (s, max_sp, max_h)
    if best is not None:
        s, max_sp, max_h = best
        if sheathed or free_height_m <= max_h + 1e-9:
            exact = "" if s == section else f" (не слабее минимального {s})"
            return True, (f"табл. 7-1: {section} при шаге {spacing_mm} ≤ {max_sp} мм, "
                          f"Hсвоб ≤{max_h} м{exact}")
        return False, (f"табл. 7-1: {section} при шаге {spacing_mm} мм допускает свободную "
                       f"высоту ≤{max_h} м, задано {free_height_m} м (нет жёсткой обшивки)")
    allowed = ", ".join(f"{s}@≤{m}мм" for s, m, _, _ in opts)
    return False, (f"табл. 7-1 ({wall}, «{load_case}») не допускает {section} при шаге "
                   f"{spacing_mm} мм; минимально требуется: {allowed}")


